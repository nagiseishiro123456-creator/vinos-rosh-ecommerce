import { expect, test } from "@playwright/test";
import { loginCustomer, prisma, reserveFromCart, resetCheckoutFixture } from "./checkout-fixture";

test("S3-04: private manual settlement validates fees and preserves discrepancy corrections", async ({ page, browser }, info) => {
  test.setTimeout(120_000);
  const { user, product } = await resetCheckoutFixture();
  await loginCustomer(page); await reserveFromCart(page);
  const order = await prisma.order.findFirstOrThrow({ where: { userId: user.id } });
  await page.locator('input[name="operationCode"]').fill(`QA-SETTLE-${info.project.name}-${Date.now()}`);
  await page.locator(".paymentReportForm").getByRole("button", { name: "Ya pagué: enviar operación a revisión" }).click();
  await expect(page).toHaveURL((url) => url.pathname === `/pedidos/${order.number}`);
  const payment = await prisma.payment.findFirstOrThrow({ where: { orderId: order.id } });
  const adminContext = await browser.newContext({ viewport: info.project.use.viewport, isMobile: info.project.use.isMobile, hasTouch: info.project.use.hasTouch });
  try {
    const admin = await adminContext.newPage();
    await admin.goto("/iniciar-sesion?callbackUrl=/admin/pagos");
    await admin.getByLabel("Correo electrónico").fill(process.env.ADMIN_EMAIL!);
    await admin.getByLabel("Contraseña", { exact: true }).fill(process.env.ADMIN_PASSWORD!);
    await admin.getByRole("button", { name: "Iniciar sesión", exact: true }).click();
    await expect(admin).toHaveURL((url) => url.pathname === "/admin/pagos");
    const approval = admin.getByRole("button", { name: "Confirmar pago", exact: true }).locator("..");
    await approval.getByRole("checkbox").check(); await approval.getByRole("button", { name: "Confirmar pago", exact: true }).click();
    await expect(admin.getByRole("status")).toHaveText("Operación registrada correctamente.");
    await page.goto(`/admin/conciliacion/${payment.id}`);
    await expect(page).toHaveURL((url) => url.pathname === "/mi-cuenta");
    await page.goto("/admin/notificaciones/configuracion");
    await expect(page).toHaveURL((url) => url.pathname === "/mi-cuenta");
    await admin.goto("/admin/notificaciones/configuracion");
    await expect(admin.getByRole("heading", { name: "Configurar confirmaciones" })).toBeVisible();
    await expect(admin.getByRole("status")).toContainText("necesita preparación");
    await expect(admin.locator('input[type="password"]')).toHaveCount(0);
    await admin.goto("/admin/conciliacion");
    await expect(admin.getByRole("heading", { name: order.number, exact: true })).toBeVisible();
    await admin.goto(`/admin/conciliacion/${payment.id}`);
    const summary = admin.getByRole("region", { name: "Resumen de conciliación" });
    await expect(summary).toContainText("Comisión pendiente");
    await admin.getByLabel("Comisión verificada (S/)", { exact: true }).fill("99.00");
    await admin.getByLabel("Reporte o extracto revisado", { exact: true }).fill("Extracto QA sin operaciones reales");
    await admin.getByLabel("Motivo del registro o corrección", { exact: true }).fill("Revisión sintética de abono y comisión");
    await admin.getByRole("checkbox").check();
    await admin.getByRole("button", { name: "Guardar conciliación" }).click();
    await expect(admin.getByText("La comisión no puede superar el pago bruto confirmado.", { exact: true })).toBeVisible();
    await expect(admin.getByLabel("Comisión verificada (S/)", { exact: true })).toHaveValue("99.00");
    await admin.getByLabel("Comisión verificada (S/)", { exact: true }).fill("2.50");
    await admin.getByLabel("Importe abonado (S/)", { exact: true }).fill("94.70");
    await admin.getByLabel("Referencia del abono", { exact: true }).fill("QA-ABONO-UNICO");
    await admin.getByLabel("Fecha del abono", { exact: true }).fill("2026-01-01");
    await admin.getByRole("checkbox").check();
    await admin.getByRole("button", { name: "Guardar conciliación" }).click();
    await expect(summary).toContainText("Diferencia por revisar");
    await expect(summary).toContainText(/Falta S\/\s*1\.00/);
    await admin.screenshot({ path: info.outputPath("s3-04-diferencia.png"), fullPage: true });
    await admin.getByLabel("Importe abonado (S/)", { exact: true }).fill("95.70");
    await admin.getByLabel("Motivo del registro o corrección", { exact: true }).fill("Corrección sintética de referencia verificada");
    await admin.getByRole("checkbox").check();
    await admin.getByRole("button", { name: "Guardar conciliación" }).click();
    await expect(summary).toContainText("Conciliado manualmente");
    await admin.reload();
    await expect(summary).toContainText("Conciliado manualmente");
    const rows = await prisma.$queryRaw<Array<{ revision: number; depositedAmount: unknown }>>`SELECT "revision", "depositedAmount" FROM "PaymentSettlement" WHERE "paymentId"=${payment.id}`;
    expect(rows).toHaveLength(1); expect(rows[0].revision).toBe(2); expect(String(rows[0].depositedAmount)).toBe("95.7");
    expect(await prisma.orderEvent.count({ where: { orderId: order.id, kind: "PAYMENT_SETTLEMENT_RECORDED" } })).toBe(2);
    expect((await prisma.order.findUniqueOrThrow({ where: { id: order.id } })).status).toBe("PAID");
    expect((await prisma.product.findUniqueOrThrow({ where: { id: product.id } })).stock).toBe(7);
    await admin.screenshot({ path: info.outputPath("s3-04-conciliado.png"), fullPage: true });
  } finally { await adminContext.close(); }
});
